// Narration captions (the display track), burned in at the bottom of the frame. Each token consumes spoken words
// in order: a token shows `s` for `n` spoken words (digits for spelled-out numbers, an acronym for its spelling),
// `br` forces a line break before it. Timing comes only from data/lyrics.json (the episode's timing.json).
import type { Lyrics } from './engine/lyrics';
import { F, font } from './engine/type';
import { rgba } from './engine/palette';
import { W, H } from './engine/gl';
import { clamp, smoothstep } from './engine/util';

import CHUNK_DATA from './captions_chunks.json';

// Generated by tools/make_captions.py from the spoken words: per line, chunks of tokens, each token
// showing `s` for `n` spoken words (digits, acronyms), `br` = line break before it.
type TokSrc = { s: string; n: number; br: boolean };
const CHUNKS = CHUNK_DATA as unknown as TokSrc[][][];
/** `?captions=0` renders a clean plate (Shorts get their own captions). */
export const CAPTIONS_ON = typeof location === 'undefined' || new URLSearchParams(location.search).get('captions') !== '0';

let muted = false;
/** Engine.renderClean: draw the HUD once more without captions (the Shorts' clean frames). */
export function muteCaptions(m: boolean) { muted = m; }

interface Tok { s: string; t0: number; t1: number; br: boolean }
interface Chunk { toks: Tok[]; start: number; end: number }
let chunks: Chunk[] = [];

export function initCaptions(ly: Lyrics) {
  chunks = [];
  ly.lines.forEach((line, li) => {
    let wi = 0;
    for (const src of CHUNKS[li] ?? []) {
      const toks: Tok[] = [];
      for (const tk of src) {
        const ws = line.words.slice(wi, wi + tk.n);
        if (ws.length < tk.n) throw new Error(`caption data overruns line ${li}`);
        wi += tk.n;
        toks.push({ s: tk.s, t0: ws[0]!.start, t1: ws[ws.length - 1]!.end, br: tk.br });
      }
      chunks.push({ toks, start: toks[0]!.t0 - 0.12, end: toks[toks.length - 1]!.t1 });
    }
    if (wi !== line.words.length) throw new Error(`caption data for line ${li} uses ${wi}/${line.words.length} words`);
  });
  for (let i = 0; i < chunks.length; i++) {
    const nx = chunks[i + 1];
    chunks[i]!.end = nx ? Math.min(nx.start, chunks[i]!.end + 1.2) : chunks[i]!.end + 1.2;
  }
}

/** Draw the active caption chunk. `ink`: the plate is bone paper, set the caption in ink. */
export function drawCaption(c: CanvasRenderingContext2D, t: number, ink: boolean) {
  if (!CAPTIONS_ON || muted) return;
  const ch = chunks.find((k) => t >= k.start && t < k.end);
  if (!ch) return;
  const a = Math.min(smoothstep(ch.start, ch.start + 0.12, t), 1 - smoothstep(ch.end - 0.1, ch.end, t));
  if (a <= 0) return;
  const size = 38, lh = 50;
  c.save();
  c.font = font(F.archivo(100, 500), size);
  c.textBaseline = 'alphabetic';
  c.textAlign = 'left';
  // lines
  const lines: Tok[][] = [[]];
  for (const tk of ch.toks) { if (tk.br) lines.push([]); lines[lines.length - 1]!.push(tk); }
  const sp = c.measureText(' ').width;
  const base = H - 74 - (lines.length - 1) * lh;
  lines.forEach((ln, i) => {
    const widths = ln.map((tk) => c.measureText(tk.s).width);
    const total = widths.reduce((s, w) => s + w, 0) + sp * (ln.length - 1);
    let x = (W - total) / 2;
    const y = base + i * lh;
    ln.forEach((tk, j) => {
      const k = clamp((t - tk.t0) / 0.08);
      const al = (0.42 + 0.58 * k) * a;
      c.fillStyle = ink ? rgba('ink', al * 0.95) : rgba('bone', al);
      c.fillText(tk.s, x, y);
      x += widths[j]! + sp;
    });
  });
  c.restore();
}
